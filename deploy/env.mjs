// Reads/updates .env.production for deploy.sh (runs on your Mac with the project's node_modules).
//   node deploy/env.mjs shell  <file>            → `export KEY='value'` lines for bash
//   node deploy/env.mjs remote <file>            → the server's runtime .env (deploy-only keys removed, derived keys added)
//   node deploy/env.mjs set    <file> KEY VALUE  → write a generated value back into the file
import { readFileSync, writeFileSync } from "node:fs";
import dotenv from "dotenv";

const [cmd, file, ...rest] = process.argv.slice(2);
const text = readFileSync(file, "utf8");
const env = dotenv.parse(text);

// Used only by deploy.sh — never written to the server's .env.
const DEPLOY_ONLY = new Set(["DEPLOY_HOST", "DEPLOY_USER", "DEPLOY_SSH_PORT", "DEPLOY_SSH_KEY", "DEPLOY_PATH", "APP_PORT", "DOMAIN", "DOMAIN_WWW", "LETSENCRYPT_EMAIL"]);
// Never allowed in production (would expose dev/test shortcuts).
const FORBIDDEN = new Set(["E2E_TEST_MODE", "ALLOW_TEST_LOGIN", "NEXT_DIST_DIR"]);

const sq = (v) => `'${String(v).replace(/'/g, `'\\''`)}'`; // bash single-quote
const dq = (v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n")}"`; // systemd/dotenv double-quote

if (cmd === "shell") {
  for (const [k, v] of Object.entries(env)) if (/^[A-Z_][A-Z0-9_]*$/.test(k)) console.log(`export ${k}=${sq(v)}`);
} else if (cmd === "remote") {
  const domain = env.DOMAIN;
  const path = env.DEPLOY_PATH || "/var/www/maison";
  const out = {};
  for (const [k, v] of Object.entries(env)) if (!DEPLOY_ONLY.has(k) && !FORBIDDEN.has(k) && v !== "") out[k] = v;
  Object.assign(out, {
    NODE_ENV: "production",
    NEXT_PUBLIC_SITE_URL: `https://${domain}`,
    AUTH_URL: `https://${domain}`,
    AUTH_TRUST_HOST: "true",
    UPLOAD_DIR: `${path}/shared/media`,
    PORT: env.APP_PORT || "3000",
    NEXT_TELEMETRY_DISABLED: "1",
  });
  console.log("# Generated by deploy.sh from .env.production — edit that file and redeploy, not this one.");
  for (const [k, v] of Object.entries(out)) console.log(`${k}=${dq(v)}`);
} else if (cmd === "set") {
  const [key, value] = rest;
  const line = `${key}=${dq(value)}`;
  const re = new RegExp(`^${key}=.*$`, "m");
  writeFileSync(file, re.test(text) ? text.replace(re, () => line) : `${text.replace(/\n?$/, "\n")}${line}\n`);
} else {
  console.error("usage: env.mjs shell|remote|set <file> [KEY VALUE]");
  process.exit(2);
}
