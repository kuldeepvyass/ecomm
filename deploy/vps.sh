#!/bin/bash
# ═══ Deploy Maison Horlogère FROM THE SERVER ITSELF (no Linux/Mac tools needed on your computer) ═══════════
# Runs on the VPS as root. Pulls the latest code from GitHub, sets the server up (first time), builds, switches
# over with a health check and automatic rollback. Your computer only needs SSH (built into Windows 10/11).
#
# First deploy (from any computer):
#   ssh root@<VPS-IP>
#   curl -fsSL https://raw.githubusercontent.com/kuldeepvyass/ecomm/main/deploy/vps.sh -o /root/maison-vps.sh
#   DOMAIN=example.com LETSENCRYPT_EMAIL=you@example.com ADMIN_EMAILS=you@example.com \
#   SMTP_USER=orders@example.com SMTP_PASSWORD='…' EMAIL_FROM='Maison Horlogère <orders@example.com>' \
#   bash /root/maison-vps.sh
#
# Every later deploy (latest code from GitHub, same settings):   bash /root/maison-vps.sh
# Other commands:   bash /root/maison-vps.sh status | rollback | setup | backup | settings
# To change a setting, pass it again, e.g.:   ADMIN_EMAILS=new@example.com bash /root/maison-vps.sh
#
# Settings are kept in /etc/maison/settings.env (root-only). AUTH_SECRET and the database password are generated.
set -Eeuo pipefail

REPO_URL_DEFAULT="https://github.com/kuldeepvyass/ecomm.git"
SETTINGS=/etc/maison/settings.env
export DEPLOY_PATH="${DEPLOY_PATH:-/var/www/maison}"
APP_USER=maison
KEEP_RELEASES=3
SETUP_VERSION_WANTED=3

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
step() { printf '\n\033[1;36m━━ %s\033[0m\n' "$*"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die()  { printf '\n\033[31m✗ %s\033[0m\n' "$*" >&2; exit 1; }
trap 'die "Stopped at line $LINENO. The live site was not switched unless noted above."' ERR

[ "$(id -u)" -eq 0 ] || die "Run as root (Hostinger: ssh root@<VPS-IP>)."
command -v apt-get >/dev/null || die "This script supports Ubuntu/Debian servers (Hostinger: Ubuntu 22.04/24.04)."
CMD="${1:-deploy}"

# ── settings: values passed now override saved ones; everything is saved for next time ─────────────────────
KEYS="DOMAIN DOMAIN_WWW LETSENCRYPT_EMAIL ADMIN_EMAILS SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASSWORD EMAIL_FROM
RESEND_API_KEY AUTH_SECRET DATABASE_URL DIRECT_URL AUTH_GOOGLE_ID AUTH_GOOGLE_SECRET CLOUDINARY_CLOUD_NAME
CLOUDINARY_API_KEY CLOUDINARY_API_SECRET NEXT_PUBLIC_APK_URL SENTRY_DSN LOG_LEVEL APP_PORT REPO_URL BRANCH"
for k in $KEYS; do eval "NEW_$k=\"\${$k-__unset__}\""; done
# shellcheck disable=SC1090
[ -f "$SETTINGS" ] && . "$SETTINGS"
for k in $KEYS; do eval "v=\"\$NEW_$k\""; [ "$v" = "__unset__" ] || eval "$k=\"\$v\""; done

DOMAIN_WWW="${DOMAIN_WWW:-true}"; SMTP_HOST="${SMTP_HOST:-smtp.hostinger.com}"; SMTP_PORT="${SMTP_PORT:-465}"
APP_PORT="${APP_PORT:-3000}"; REPO_URL="${REPO_URL:-$REPO_URL_DEFAULT}"; BRANCH="${BRANCH:-main}"; LOG_LEVEL="${LOG_LEVEL:-info}"
[ -n "${AUTH_SECRET:-}" ] || AUTH_SECRET="$(openssl rand -base64 32)"
[ -n "${DATABASE_URL:-}" ] || DATABASE_URL="postgresql://maison:$(openssl rand -hex 24)@127.0.0.1:5432/maison"

save_settings() {
  install -d -m 700 /etc/maison
  local tmp; tmp="$(mktemp)"
  echo "# Maison Horlogère deploy settings — written by vps.sh. Pass a KEY=value to vps.sh to change one." > "$tmp"
  for k in $KEYS; do
    local v; eval "v=\"\${$k:-}\""
    printf "%s='%s'\n" "$k" "$(printf '%s' "$v" | sed "s/'/'\\\\''/g")" >> "$tmp"
  done
  install -m 600 "$tmp" "$SETTINGS"; rm -f "$tmp"
}

require_settings() {
  local missing=""
  for v in DOMAIN LETSENCRYPT_EMAIL ADMIN_EMAILS EMAIL_FROM; do eval "[ -n \"\${$v:-}\" ]" || missing="$missing $v"; done
  if [ -z "${RESEND_API_KEY:-}" ] && { [ -z "${SMTP_USER:-}" ] || [ -z "${SMTP_PASSWORD:-}" ]; }; then missing="$missing SMTP_USER/SMTP_PASSWORD"; fi
  [ -z "$missing" ] || die "Missing settings:$missing  (pass them as KEY=value before 'bash $0' — see the top of this script)"
  case "$DOMAIN" in http*|*/*|*" "*) die "DOMAIN should be just the name, e.g. example.com";; esac
}

health() { curl -fsS --max-time 5 "http://127.0.0.1:$APP_PORT/api/health" 2>/dev/null; }
wait_healthy() { local _; for _ in $(seq 1 45); do health | grep -q '"ok":true' && return 0; sleep 2; done; return 1; }
switch_to() {
  ln -sfn "$DEPLOY_PATH/releases/$1" "$DEPLOY_PATH/current.tmp" && mv -Tf "$DEPLOY_PATH/current.tmp" "$DEPLOY_PATH/current"
  systemctl restart maison
}

# The app's runtime .env (double-quoted, escaped for systemd and dotenv).
write_app_env() {
  local tmp; tmp="$(mktemp)"
  dq() { printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"; }
  {
    echo "# Generated by deploy/vps.sh from /etc/maison/settings.env — change settings by re-running vps.sh."
    for k in ADMIN_EMAILS SMTP_HOST SMTP_PORT SMTP_USER SMTP_PASSWORD EMAIL_FROM RESEND_API_KEY AUTH_SECRET DATABASE_URL DIRECT_URL \
             AUTH_GOOGLE_ID AUTH_GOOGLE_SECRET CLOUDINARY_CLOUD_NAME CLOUDINARY_API_KEY CLOUDINARY_API_SECRET NEXT_PUBLIC_APK_URL SENTRY_DSN LOG_LEVEL; do
      local v; eval "v=\"\${$k:-}\""
      [ -n "$v" ] && echo "$k=$(dq "$v")"
    done
    echo "NODE_ENV=\"production\""
    echo "NEXT_PUBLIC_SITE_URL=\"https://$DOMAIN\""
    echo "AUTH_URL=\"https://$DOMAIN\""
    echo "AUTH_TRUST_HOST=\"true\""
    echo "UPLOAD_DIR=\"$DEPLOY_PATH/shared/media\""
    echo "PORT=\"$APP_PORT\""
    echo "NEXT_TELEMETRY_DISABLED=\"1\""
  } > "$tmp"
  install -o "$APP_USER" -g "$APP_USER" -m 600 "$tmp" "$DEPLOY_PATH/shared/.env"; rm -f "$tmp"
}

fetch_code() {
  command -v git >/dev/null || { apt-get update -qq && apt-get install -y -qq git >/dev/null; }
  if [ -d "$DEPLOY_PATH/repo/.git" ]; then
    git -C "$DEPLOY_PATH/repo" remote set-url origin "$REPO_URL"
    git -C "$DEPLOY_PATH/repo" fetch -q --depth 1 origin "$BRANCH"
    git -C "$DEPLOY_PATH/repo" reset -q --hard FETCH_HEAD
  else
    install -d "$DEPLOY_PATH"
    git clone -q --depth 1 --branch "$BRANCH" "$REPO_URL" "$DEPLOY_PATH/repo"
  fi
  ok "code at $(git -C "$DEPLOY_PATH/repo" log -1 --format='%h %s' | cut -c1-70)"
}

server_setup() {
  local db_name="" db_user="" db_pass="" local_db=0
  if [[ "$DATABASE_URL" =~ ^postgres(ql)?://([^:@/]+):([^@]*)@([^:/]+)(:[0-9]+)?/([^?]+) ]]; then
    db_user="${BASH_REMATCH[2]}"; db_pass="${BASH_REMATCH[3]}"; db_name="${BASH_REMATCH[6]}"
    case "${BASH_REMATCH[4]}" in 127.0.0.1|localhost) local_db=1 ;; esac
  fi
  local ssh_port="${SSH_CONNECTION:-}"; ssh_port="$(echo "$ssh_port" | awk '{print $4}')"; ssh_port="${ssh_port:-22}"
  local server_ip; server_ip="$(curl -fsS4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
  DOMAIN="$DOMAIN" DOMAIN_WWW="$DOMAIN_WWW" LETSENCRYPT_EMAIL="$LETSENCRYPT_EMAIL" APP_PORT="$APP_PORT" \
    APP_USER="$APP_USER" SERVER_IP="$server_ip" SSH_PORT="$ssh_port" LOCAL_DB="$local_db" DB_NAME="$db_name" DB_USER="$db_user" DB_PASS="$db_pass" \
    bash "$DEPLOY_PATH/repo/deploy/server-setup.sh"
}

deploy() {
  require_settings
  save_settings
  step "Getting the latest code from GitHub ($REPO_URL, $BRANCH)"
  fetch_code
  if [ "$(cat "$DEPLOY_PATH/.setup-version" 2>/dev/null || true)" != "$SETUP_VERSION_WANTED" ] || [ "$CMD" = "setup" ]; then
    step "Setting up the server (first time ~5–10 minutes)"
    server_setup
  else
    ok "server already set up (run: bash $0 setup to redo it)"
  fi
  [ "$CMD" = "setup" ] && return 0

  step "Settings"
  write_app_env
  ok "app settings written (readable only by the app)"

  local release prev
  release="$(date +%Y%m%d-%H%M%S)"
  prev="$(readlink "$DEPLOY_PATH/current" 2>/dev/null | xargs -r basename || true)"
  step "Preparing release $release"
  install -d -o "$APP_USER" -g "$APP_USER" "$DEPLOY_PATH/releases/$release"
  git -C "$DEPLOY_PATH/repo" archive HEAD | tar -x -C "$DEPLOY_PATH/releases/$release"
  chown -R "$APP_USER:$APP_USER" "$DEPLOY_PATH/releases/$release"

  step "Building (the live site keeps running meanwhile)"
  sudo -u "$APP_USER" -H bash "$DEPLOY_PATH/releases/$release/deploy/release.sh" "$DEPLOY_PATH/releases/$release" "$DEPLOY_PATH/shared" \
    || { rm -rf "${DEPLOY_PATH:?}/releases/$release"; die "Build failed — the live site was NOT changed."; }

  step "Going live"
  switch_to "$release"
  if wait_healthy; then
    ok "release $release is live and healthy"
  else
    warn "new release failed its health check — recent logs:"; journalctl -u maison -n 40 --no-pager || true
    [ -n "$prev" ] && { switch_to "$prev"; die "Rolled back to $prev — the site runs the previous version."; }
    die "First release failed to start — see the logs above (journalctl -u maison)."
  fi
  (cd "$DEPLOY_PATH/releases" && ls -1d -- */ | sed 's#/##' | sort | head -n -"$KEEP_RELEASES" | xargs -r rm -rf)

  local scheme=https; [ -f "$DEPLOY_PATH/.ssl-pending" ] && scheme=http
  printf '\n'; bold "✓ Deployed $release → $scheme://$DOMAIN"
  [ "$scheme" = "http" ] && warn "HTTPS pending: point $DOMAIN (A record) at this server, wait a few minutes, then run: bash $0 setup"
  if [ ! -f "$DEPLOY_PATH/shared/.welcomed" ]; then
    printf '\n'; bold "Next steps:"
    echo "  1. Sign in at $scheme://$DOMAIN/sign-in with $ADMIN_EMAILS (a 6-digit code is emailed) — you're the admin."
    echo "  2. Admin → Settings: store name, address, GSTIN and your UPI ID (payments stay off until it's set)."
    touch "$DEPLOY_PATH/shared/.welcomed"
  fi
}

case "$CMD" in
  deploy|setup) deploy ;;
  status)
    systemctl --no-pager status maison | head -n 8 || true
    echo "release: $(readlink "$DEPLOY_PATH/current" 2>/dev/null | xargs -r basename)"
    printf 'health: '; health || echo "not responding"; echo ;;
  rollback)
    cur="$(readlink "$DEPLOY_PATH/current" | xargs basename)"
    prev="$(ls -1 "$DEPLOY_PATH/releases" | sort | grep -B1 -x "$cur" | head -n1)"
    [ -n "$prev" ] && [ "$prev" != "$cur" ] || die "No earlier release to roll back to."
    switch_to "$prev"; wait_healthy && ok "rolled back to $prev" || die "Previous release isn't healthy either — journalctl -u maison" ;;
  backup) f="$(sudo -u "$APP_USER" /usr/local/bin/maison-backup)"; ok "database backup: $f" ;;
  settings) sed -E "s/^((SMTP_PASSWORD|AUTH_SECRET|AUTH_GOOGLE_SECRET|CLOUDINARY_API_SECRET|RESEND_API_KEY)=).+/\1'<hidden>'/; s#(postgresql://[^:]+:)[^@]+@#\1<hidden>@#" "$SETTINGS" ;;
  *) die "Unknown command '$CMD' (use: deploy | setup | status | rollback | backup | settings)" ;;
esac
